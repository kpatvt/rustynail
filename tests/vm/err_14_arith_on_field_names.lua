local t = {x = {}}
print(pcall(function() return t.x + 1 end))
print(pcall(function() return t.y + 1 end))
print(pcall(function() return 1 + t.x end))
print(pcall(function() return t.x.z + 1 end))
print(pcall(function() return t["x"] + 1 end))
print(pcall(function() local k = "x" return t[k] + 1 end))
print(pcall(function() return t[1] + 1 end))
print(pcall(function() return -t.x end))
print(pcall(function() return t.x | 1 end))
print(pcall(function() return t.x .. "s" end))
print(pcall(function() return #t.y end))
print(pcall(function() return t.x < 1 end))
print(pcall(function() t.y.z = 1 end))
print(pcall(function() t.x.y.z = 1 end))
