local function mk(name) return setmetatable({}, {__close = function(_, e) print("close", name, e) end}) end
local co = coroutine.create(function()
  local a <close> = mk("a")
  local b <close> = mk("b")
  coroutine.yield(1)
  print("not reached")
end)
print(coroutine.resume(co))
print(coroutine.close(co))
print(coroutine.status(co))
local co2 = coroutine.create(function()
  local a <close> = setmetatable({}, {__close = function() error("cerr") end})
  coroutine.yield()
end)
coroutine.resume(co2)
print(coroutine.close(co2))
print(coroutine.status(co2))
local co3 = coroutine.wrap(function()
  local a <close> = setmetatable({}, {__close = function() coroutine.yield("in close") print("after yield in close") end})
  return "ret"
end)
print(co3()) print(co3())
print(coroutine.close(coroutine.create(print)))
print(pcall(coroutine.close, coroutine.running()))
