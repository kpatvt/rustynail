local t = setmetatable({}, {__index = function(t, k) error("idx " .. k, 0) end})
print(pcall(function() return t.foo end))
local u = setmetatable({}, {__add = function() error({}, 0) end})
local ok, e = pcall(function() return u + 1 end)
print(ok, type(e))
local v = setmetatable({}, {__call = function() error("called", 0) end})
print(pcall(v))
local w = setmetatable({}, {__newindex = function() error("ni", 0) end})
print(pcall(function() w.x = 1 end))
local lt = setmetatable({}, {__lt = function() error("lt", 0) end})
print(pcall(function() return lt < lt end))
local cc = setmetatable({}, {__concat = function() error("cc", 0) end})
print(pcall(function() return cc .. "x" end))
local ln = setmetatable({}, {__len = function() error("len", 0) end})
print(pcall(function() return #ln end))
local eq = setmetatable({}, {__eq = function() error("eq", 0) end})
print(pcall(function() return eq == setmetatable({}, getmetatable(eq)) end))
