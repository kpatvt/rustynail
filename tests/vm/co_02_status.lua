local co
co = coroutine.create(function()
  print(coroutine.status(co), coroutine.running() == co, coroutine.isyieldable())
  local inner = coroutine.create(function() print(coroutine.status(co)) coroutine.yield() end)
  coroutine.resume(inner)
  print(coroutine.status(inner))
  coroutine.yield()
end)
print(coroutine.status(co))
coroutine.resume(co)
print(coroutine.status(co))
coroutine.resume(co)
print(coroutine.status(co))
print(coroutine.resume(co))
print(coroutine.resume(coroutine.running()))
print(select(2, coroutine.running()), coroutine.isyieldable())
print(pcall(coroutine.status, 1))
print(pcall(coroutine.resume, nil))
print(pcall(coroutine.create, 1))
print(pcall(coroutine.wrap))
