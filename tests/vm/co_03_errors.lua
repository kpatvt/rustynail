print(coroutine.resume(co))
print(coroutine.status(co), coroutine.resume(co))
local w = coroutine.wrap(function() error({code = 7}) end)
local ok, e = pcall(w) print(ok, type(e), e.code)
w = coroutine.wrap(function() error("str") end)
print(pcall(w))
w = coroutine.wrap(function() coroutine.yield(1) end)
w() w()
print(pcall(w))
