local C = dofile("_common.lua")
local P, hex, show = C.P, C.hex, C.show
local buf = require("string.buffer")
print("loaded", package.loaded["string.buffer"] == buf, type(buf.new), type(buf.encode), type(buf.decode), string.buffer)

local b = buf.new()
print("type", type(b))
P("put-multi", function() b:put("a", 1, 2.5, "b") return tostring(b), #b end)
P("put-tbl", b.put, b, {})
P("put-bool", b.put, b, true)
P("put-nil", b.put, b, nil)
P("put-none", function() return b:put() == b end)
P("put-tostring", function()
  local x = buf.new()
  x:put(setmetatable({}, { __tostring = function() return "T!" end }), "|", -7, "|", 1e100)
  return tostring(x)
end)
P("get0", function() b:reset() b:put("xx") return b:get(0) end)
P("get-1", b.get, b, -1)
P("get100", b.get, b, 100)
P("getfrac", function() b:set("abc") return b:get(1.5) end)
P("getstr", b.get, b, "a")
P("getn", function() b:set("abc") return b:get(1, 1, 1) end)
P("get4", function() b:set("abcdef") return b:get(1, 1, 1, 1) end)
P("get-all", function() b:set("abcdef") return b:get() end)
P("get-nilarg", function() b:set("abcdef") return b:get(nil) end)
P("get-then-rest", function() b:set("abcdef") local x = b:get(2) return x, #b, tostring(b), b:get() end)
P("skip", function() b:set("abcdef") b:skip(2) return tostring(b) end)
P("skipbig", function() b:set("abc") b:skip(100) return #b end)
P("skipneg", b.skip, b, -1)
P("skipstr", b.skip, b, "x")
P("putf", function() b:reset() b:putf("%d-%s-%5.2f %q %x %c %5s|%-5s|", 42, "z", 3.14159, "q\n", 255, 65, "ab", "cd") return tostring(b) end)
P("putf-bad", b.putf, b, "%d", "x")
P("putf-none", b.putf, b)
P("putf-%s-nil", function() b:reset() b:putf("%s %s", nil, true) return tostring(b) end)
P("putf-chain", function() b:reset() return b:putf("%d", 1):putf("%d", 2):put("!"):tostring() end)
P("concat", function() b:set("x") return tostring(b .. "t"), tostring("t" .. b), tostring(b .. b), tostring(b .. 5) end)
print("concat-bad", (pcall(function() return b .. {} end)))
P("len", function() b:set("hello") return #b, b:skip(2) == b, #b end)
P("free", function() b:set("x") b:free() return #b, tostring(b) end)
P("reuse-after-free", function() b:free() b:put("again") return tostring(b) end)
P("reset", function() b:put("junk") b:reset() return #b, tostring(b) end)
P("new-1", buf.new, -1)
P("new-str", buf.new, "x")
P("new-100", function() return type(buf.new(100)) end)
P("new-dict1", function() return type(buf.new({ dict = 1 })) end)
P("new-dictnotstr", buf.new, { dict = { 1 } })
P("new-mtnott", function() return type(buf.new({ metatable = 1 })) end)
P("new-mtstr", buf.new, { metatable = { "x" } })
P("new-foo", function() return type(buf.new({ foo = 1 })) end)
P("new-true", buf.new, true)
P("new-size+opt", function() return type(buf.new(10, {})) end)
P("new-huge", buf.new, 2 ^ 40)
P("new-nan", buf.new, 0 / 0)
P("tostring", function() local x = buf.new() x:put("abc") return x:tostring(), tostring(x) end)
P("tostring-keeps", function() local x = buf.new() x:put("abc") x:get(1) return x:tostring(), #x end)
P("chain", function()
  local x = buf.new()
  return x:put("a") == x, x:set("x") == x, x:skip(0) == x, x:reset() == x, x:putf("%d", 1) == x, x:encode(1) == x
end)
P("big-put", function()
  local x = buf.new()
  local s = ("0123456789"):rep(1000)
  for i = 1, 50 do x:put(s) end
  local n = #x
  local first = x:get(10)
  return n, first, #x
end)
P("binary", function()
  local x = buf.new()
  x:put("a\0b", "\255\254")
  return hex(x:tostring()), #x
end)
P("interleave", function()
  local x = buf.new()
  local out = {}
  for i = 1, 200 do
    x:put("item", i, ";")
    if i % 7 == 0 then out[#out + 1] = x:get(5) end
    if i % 31 == 0 then x:skip(3) end
  end
  return #x, #table.concat(out), table.concat(out, ","):sub(1, 40)
end)
P("get-multi-ret-count", function() b:set("abcdefgh") return select("#", b:get(1, 2, 3)) end)
P("encode-none", buf.encode)
P("decode-none", buf.decode)
P("decode-num", buf.decode, 5)
P("decode-tbl", buf.decode, {})
P("encode-buf", function() return buf.encode(buf.new()) end)
