local m = require "samplemod"
print(m.version())
local v = m.new(3)
v:set(1, 1.5); v:set(2, 2); v:set(3, -1)
print(#v, v:len(), v:get(2), tostring(v), v:tag())
print(pcall(v.get, v, 9))
print(pcall(m.new, -1))
print(pcall(m.new, "x"))
print(pcall(v.set, 42, 1, 1))
print(m.new(2) == m.new(2), v == m.new(3))
print(m.sum({1, 2, 3, x = 4.5, y = "no", 10}))
local c = m.counter(10, 5); print(c(), c(), c())
print(m.callback(function(a, b) return a + b, "r" end, 3, 4))
print(m.callback(function() error("inside") end))
print(m.callback(function() error({}) end) ~= nil)
local co = coroutine.wrap(function() local out = {} for x in m.gen, 3 do out[#out + 1] = x end return table.concat(out, ",") end)
print(pcall(co))
local gen = coroutine.wrap(function() return m.gen(3) end)
print(gen(), gen(), gen(), gen())
print(pcall(m.fail, "string"))
local ok, e = pcall(m.fail, "table"); print(ok, type(e), e.info)
print(pcall(m.fail, "arg"))
print(pcall(m.fail, "type", 1))
print(m.fmt(1, 2.5, "s", nil, true, v, setmetatable({}, {__tostring = function() return "TS" end})))
print(#m.bigstring(5000), m.bigstring(3):sub(1, 20))
print(m.refs({}) , select('#', m.refs(1)))
