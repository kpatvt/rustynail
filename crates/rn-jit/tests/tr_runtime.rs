/// Permissions of the mapping that contains `addr` in `/proc/self/maps` (`None`: not mapped).
fn map_perms(addr: usize) -> Option<String> {
    let maps = std::fs::read_to_string("/proc/self/maps").unwrap();
    for l in maps.lines() {
        let mut it = l.split_whitespace();
        let (range, perms) = (it.next()?, it.next()?);
        let (lo, hi) = range.split_once('-')?;
        let (lo, hi) = (
            usize::from_str_radix(lo, 16).unwrap(),
            usize::from_str_radix(hi, 16).unwrap(),
        );
        if (lo..hi).contains(&addr) {
            return Some(perms.to_string());
        }
    }
    None
}

