// ---- 6. TR18: flush is deferred while an exit handler runs ----------------------------------------------------

static HANDLER_SEEN_ALIVE: AtomicU64 = AtomicU64::new(0);
static HANDLER_CALLS: AtomicU64 = AtomicU64::new(0);

/// A stand-in for the Rust exit handler, called from trace code.
unsafe extern "C" fn fake_handler(th: *mut Thread, _ci: *mut CallInfo, slot: u32, gen: u32) -> u32 {
    // SAFETY: called from the fake trace with the running thread.
    let mut st = unsafe { jit_hooks::state_from_thread(th.cast()) };
    let id = TrId { slot, gen };
    c::handler_enter(&mut st);
    c::request_flush(&mut st, id, FlushWhy::Rerec);
    // the trace block we were called from must still be allocated (parked in the graveyard)
    if c::grave_blocks(&mut st).len() == 1 {
        HANDLER_SEEN_ALIVE.fetch_add(1, Ordering::Relaxed);
    }
    HANDLER_CALLS.fetch_add(1, Ordering::Relaxed);
    c::handler_leave(&mut st);
    0
}

static GC_HANDLER_GRAVE: AtomicU64 = AtomicU64::new(0);
static GC_HANDLER_CALLS: AtomicU64 = AtomicU64::new(0);

/// An exit handler that runs the collector (stack growth or sunk allocations can do that): the collection frees
/// the inlined callee of the very trace this handler was called from.
unsafe extern "C" fn gc_handler(th: *mut Thread, ci: *mut CallInfo, _slot: u32, _gen: u32) -> u32 {
    // SAFETY: called from the fake trace with the running thread.
    let mut st = unsafe { jit_hooks::state_from_thread(th.cast()) };
    c::handler_enter(&mut st);
    // the fake trace runs mid-frame: like a real helper call, expose the whole frame to the collector
    // SAFETY: `ci` is the running Lua frame.
    st.set_top(unsafe { (*ci).top });
    st.collect(false);
    if c::grave_blocks(&mut st).len() == 1 {
        GC_HANDLER_GRAVE.fetch_add(1, Ordering::Relaxed);
    }
    GC_HANDLER_CALLS.fetch_add(1, Ordering::Relaxed);
    c::handler_leave(&mut st);
    0
}

#[test]
fn deferred_flush_requested_inside_the_exit_handler_runs_at_the_next_safe_point() {
    let (mut st, f, pc) = with_f(cfg_on(1000));
    HANDLER_SEEN_ALIVE.store(0, Ordering::Relaxed);
    HANDLER_CALLS.store(0, Ordering::Relaxed);
    let n = AtomicU64::new(0);
    let id = c::begin_recording(&mut st, f, pc).unwrap();
    let land = head(&mut st, f).pcl_addr;
    // the trace calls the handler and then keeps executing in its own block (a freed block would be reused/poisoned)
    let h = Some((fake_handler as *const () as usize as u64, id.slot, id.gen));
    let tid = c::install(&mut st, id, fake(&n, land, h)).unwrap();
    assert_eq!(tid, id);
    assert_eq!(exec(&mut st, "return f(10)"), "55");
    // the head was detached at once: the trace is entered and reports exactly once
    assert_eq!(HANDLER_CALLS.load(Ordering::Relaxed), 1);
    assert_eq!(n.load(Ordering::Relaxed), 1);
    assert_eq!(
        HANDLER_SEEN_ALIVE.load(Ordering::Relaxed),
        1,
        "TR18: the trace was freed while its exit handler was running"
    );
    // the next back-edge (`jit_tr_hot`) or `rt::enter` is a safe point: block and metadata are retired
    assert!(!c::trace_live(&mut st, id));
    assert_eq!(c::counts(&mut st), (0, 0));
    assert_eq!(c::tr_stats(&mut st).deferred, 1);
    assert_eq!(head(&mut st, f).rerec, 1);
}

