#[test]
fn utf8_semantics() {
    let cases = s(&[
        "return J(utf8.charpattern == '[\\0-\\x7F\\xC2-\\xFD][\\x80-\\xBF]*', #utf8.charpattern)",
        "return J(utf8.char(72, 228, 8364, 128512), utf8.char(), utf8.char(0), #utf8.char(0x7FFFFFFF))",
        "return J(utf8.len('h\\u{e9}llo'), utf8.len(''), utf8.len('\\xff'), utf8.len('abc', 4), utf8.len('abc', 2, 2), utf8.len('\\u{D800}'), utf8.len('\\u{D800}', 1, -1, true))",
        "return J(utf8.codepoint('h\\u{e9}llo', 1, -1))",
        "return J(utf8.codepoint('abc'), utf8.codepoint('abc', 2), utf8.codepoint('abc', -1), utf8.codepoint('abc', 1, 0))",
        "return J(utf8.offset('h\\u{e9}llo', 3), utf8.offset('h\\u{e9}llo', -1), utf8.offset('h\\u{e9}llo', 0, 3), utf8.offset('h\\u{e9}llo', 10), utf8.offset('abc', 4), utf8.offset('abc', 5))",
        "local t = {} for p, c in utf8.codes('h\\u{e9}\\u{20AC}x') do t[#t+1] = p..':'..c end return table.concat(t, ' ')",
        "local t = {} for p, c in utf8.codes('ab') do t[#t+1] = p..':'..c end return table.concat(t, ' ')",
        "local t = {} for p, c in utf8.codes('') do t[#t+1] = p..':'..c end return #t",
        "return J(pcall(function() for p, c in utf8.codes('a\\xffb') do end end))",
        "return J(pcall(function() for p, c in utf8.codes('\\x80') do end end))",
        "local t = {} for p, c in utf8.codes('\\u{D800}a', true) do t[#t+1] = p..':'..c end return table.concat(t, ' ')",
        "return J(pcall(function() for p, c in utf8.codes('\\u{D800}a') do end end))",
        "local r = {} for ch in ('h\\u{e9}llo'):gmatch(utf8.charpattern) do r[#r+1] = #ch end return table.concat(r, ',')",
        "return J(utf8.char(0x10FFFF):byte(1, -1))",
        "return J(utf8.char(0x7FF):byte(1, -1))",
        "return J(utf8.codepoint(utf8.char(0x7FFFFFFF), 1, 1, true))",
        "return J(pcall(utf8.codepoint, utf8.char(0x7FFFFFFF)))",
        "return J(utf8.len('\\u{7FFFFFFF}', 1, -1, true), utf8.len('\\u{7FFFFFFF}'))",
        "return J(utf8.len('abc', 1, 10 ^ 10 // 1 | 0) )",
        "return J(pcall(utf8.len, 'abc', 1, 4), pcall(utf8.len, 'abc', 5), pcall(utf8.len, 'abc', 0))",
        "local f, s, i = utf8.codes('ab') return J(type(f), s, i, f(s, i))",
        "local f, s, i = utf8.codes('ab') return J(f(s, 2), f(s, 5), f(s, -1))",
    ]);
    assert_batch(&cases);
}
