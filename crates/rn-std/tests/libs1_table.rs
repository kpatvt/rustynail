const NAMES: &[&str] = &[
    "concat", "create", "insert", "pack", "unpack", "remove", "move", "sort",
];

#[test]
fn error_matrix() {
    assert_batch(&call_matrix("table", NAMES, ARGS));
}

fn s(v: &[&str]) -> Vec<String> {
    v.iter().map(|x| x.to_string()).collect()
}

#[test]
fn semantics() {
    let cases = s(&[
        "local t = {} table.insert(t, 'a') table.insert(t, 'b') table.insert(t, 1, 'c') return table.concat(t, ',')",
        "local t = {1,2,3} table.insert(t, 2, 'x') table.insert(t, #t+1, 'e') return table.concat(t, ',')",
        "local t = {1,2,3} return J(table.remove(t), table.remove(t, 1), table.remove(t, 5), #t, table.remove({}), table.remove({}, 0), table.remove({}, 1))",
        "local t = {1,2,3} return J(table.remove(t, #t+1), pcall(table.remove, t, #t+2), pcall(table.remove, t, 0))",
        "local t = {n=0} return J(table.remove(t, 0), pcall(table.remove, t, -1))",
        "return J(table.unpack({1,2,3}), table.unpack({1,2,3}, 2), table.unpack({1,2,3}, 2, 3), table.unpack({1,2,3}, 3, 2), table.unpack({}, 1, 3))",
        "return J(select('#', table.unpack({}, 1, 0)), select('#', table.unpack({n=3}, 1, 3)), pcall(table.unpack, {}, 1, 1e8), pcall(table.unpack, {}, math.mininteger, math.maxinteger))",
        "local p = table.pack(1, nil, 3, nil) return J(p.n, #p >= 0, p[1], p[2], p[3], select('#', table.unpack(p, 1, p.n)))",
        "return J(table.pack().n, next(table.pack()))",
        "return table.concat({1, 2, 3}, ', ', 2, 3)",
        "return J(table.concat({}), table.concat({}, 'x'), table.concat({'a'}, 'x'), table.concat({1, 2.5, 'x'}, '-'), table.concat({'a','b','c'}, '', 3, 3), table.concat({'a','b'}, ',', 3))",
        "return J(pcall(table.concat, {1, {}, 3}), pcall(table.concat, {1, 2}, ',', 1, 3), pcall(table.concat, {true}))",
        "local t = {5, 2, 8, 1, 9, 3} table.sort(t) return table.concat(t, ',')",
        "local t = {5, 2, 8, 1, 9, 3} table.sort(t, function(a, b) return a > b end) return table.concat(t, ',')",
        "local t = {'b', 'a', 'd', 'c'} table.sort(t) return table.concat(t, ',')",
        "local t = {3, 1, 2, 'x'} return J(pcall(table.sort, t))",
        "local t = {} for i = 1, 100 do t[i] = (i * 37) % 101 end table.sort(t) local ok = true for i = 2, 100 do if t[i-1] > t[i] then ok = false end end return ok",
        "local t = {} for i = 1, 1000 do t[i] = (i * 7919) % 1009 end table.sort(t, function(a, b) return a > b end) local ok = true for i = 2, 1000 do if t[i-1] < t[i] then ok = false end end return ok .. t[1] .. t[1000]",
        "local log = {} local t = {4, 2, 7, 1, 9, 3, 8, 5, 6, 0} table.sort(t, function(a, b) log[#log+1] = a..'<'..b return a < b end) return table.concat(log, ' ')",
        "local log = {} local t = {} for i = 1, 150 do t[i] = (i * 31) % 151 end table.sort(t, function(a, b) log[#log+1] = a..b return a < b end) return #log .. ':' .. table.concat(t, ',', 1, 10)",
        "local t = {} for i = 1, 300 do t[i] = i end table.sort(t, function(a, b) return a > b end) return t[1] .. ',' .. t[300]",
        "local t = {} for i = 1, 300 do t[i] = 5 end table.sort(t) return #t",
        "local t = {} for i = 1, 200 do t[i] = i % 3 end return pcall(table.sort, t, function(a, b) return true end)",
        "local t = {1, 2, 3, 4, 5} return pcall(table.sort, t, function(a, b) return true end)",
        "local t = {3, 2, 1} return pcall(table.sort, t, function(a, b) return a <= b end)",
        "local t = {1,2,3} table.sort(t, function(a, b) error('cmp') end)",
        "local t = setmetatable({}, {__index = function(t, k) return nil end}) return pcall(table.sort, t)",
        "local t = {'a', 'B', 'c'} table.sort(t, function(a, b) return a:lower() < b:lower() end) return table.concat(t)",
        "local mt = {__lt = function(a, b) return a.v < b.v end} local t = {} for i, v in ipairs{3, 1, 2} do t[i] = setmetatable({v = v}, mt) end table.sort(t) return t[1].v .. t[2].v .. t[3].v",
        "local t = {1,2,3,4,5} return J(table.move(t, 2, 4, 1) == t, table.concat(t, ','))",
        "local t = {1,2,3,4,5} table.move(t, 1, 3, 3) return table.concat(t, ',')",
        "local t = {1,2,3} local u = table.move(t, 1, 3, 2, {}) return J(u[1], u[2], u[3], u[4])",
        "return J(#table.move({}, 1, 0, 1), #table.move({1,2,3}, 1, 3, 1, {}), pcall(table.move, {}, 1, math.maxinteger, 2))",
        "return J(pcall(table.move, {}, 0, math.maxinteger, 1), pcall(table.move, {}, math.mininteger, -1, 1), pcall(table.move, {1}, 1, 1, math.maxinteger))",
        "local p = setmetatable({}, {__index = function(t, k) return k * 10 end, __newindex = function(t, k, v) rawset(t, k, v + 1) end}) table.move(p, 1, 3, 1, p) return J(rawget(p, 1), rawget(p, 2), rawget(p, 3))",
        "local log = {} local p = setmetatable({}, {__newindex = function(t, k, v) log[#log+1] = k..'='..v rawset(t, k, v) end}) table.insert(p, 'a') table.insert(p, 'b') table.insert(p, 1, 'c') return table.concat(log, ' ')",
        "local p = setmetatable({}, {__len = function() return 3 end, __index = function(t, k) return 'v' .. k end}) return J(table.concat(p, ','), table.unpack(p))",
        "local p = setmetatable({}, {__len = function() return 2 end, __index = function(t, k) return k end, __newindex = function(t, k, v) rawset(t, k, v) end}) return J(table.remove(p), table.remove(p, 1), rawget(p, 1), rawget(p, 2))",
        "return J(pcall(table.insert, setmetatable({}, {__newindex = type}), 1))",
        "return J(pcall(table.insert, 'abc', 1), pcall(table.concat, 'abc'), pcall(table.unpack, 'abc'), pcall(table.sort, 'abc'))",
        "return J(pcall(table.insert, io.stdout, 1), pcall(table.concat, io.stdout))",
        "return J(#table.create and 1 or 0)",
        "local t = table.create and table.create(10, 5) or {} return J(type(t), #t)",
        "return J(table.create and pcall(table.create, -1) or 'n', table.create and pcall(table.create, 1, 2^31) or 'n')",
        "return J(type(table.unpack), table.unpack == unpack)",
        "local t = {} t[1] = 1 t[2] = 2 t[4] = 4 return #t == 2 or #t == 4",
        "local t = setmetatable({}, {__len = function() return math.maxinteger end}) return J(pcall(table.insert, t, 1))",
        "local t = setmetatable({}, {__len = function() return math.maxinteger end, __newindex = function(t, k, v) rawset(t, 'k', k) end}) table.insert(t, 1) return J(rawget(t, 'k'), pcall(table.insert, t, math.mininteger, 0))",
        "local big = {} for i = 1, 5000 do big[i] = i end return J(select('#', table.unpack(big)), (table.unpack(big)), select(5000, table.unpack(big)))",
        "local t = {} for i = 1, 200 do table.insert(t, 1, i) end for i = 1, 100 do table.remove(t, 1) end return J(#t, t[1], t[100])",
        "local t = {10, 20, 30} for i = 1, 3 do table.insert(t, 2, i) end return table.concat(t, ',')",
        "local t = {1, 2, 3} t[#t + 1] = 4 return J(table.unpack(t))",
        "return J(pcall(table.insert, {1,2,3}, 5, 'x'), pcall(table.insert, {1,2,3}, 0, 'x'), pcall(table.insert, {1,2,3}, 4, 'x'))",
    ]);
    assert_batch(&cases);
}
