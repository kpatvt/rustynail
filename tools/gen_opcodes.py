#!/usr/bin/env python3
"""Generate crates/rn-core/src/ver/v5X/opcodes_gen.rs from vendored lopcodes.c.
Usage: tools/gen_opcodes.py   (regenerates both versions; output is committed)"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
def camel(n):
    c = ''.join(w.capitalize() for w in n.split('_'))
    return "SelfOp" if c == "Self" else c  # `Self` is a Rust keyword
for ver, short in (("5.4","v54"),("5.5","v55")):
    src = (root/f"vendor/lua-{ver}/src/lopcodes.c").read_text()
    body = src[src.index("luaP_opmodes"):]
    rows = re.findall(r"opmode\((\d), *(\d), *(\d), *(\d), *(\d), *(\w+)\)\s*/\* OP_(\w+)\s*\*/", body)
    assert len(rows) in (83, 85), (ver, len(rows))
    out = [f"// @generated by tools/gen_opcodes.py from vendor/lua-{ver}/src/lopcodes.c -- DO NOT EDIT",
           
           "/// Instruction formats (`enum OpMode` in lopcodes.h).",
           "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
           "pub enum OpMode { IABC, IvABC, IABx, IAsBx, IAx, IsJ }", ""]
    modes = {"iABC":"IABC","ivABC":"IvABC","iABx":"IABx","iAsBx":"IAsBx","iAx":"IAx","isJ":"IsJ"}
    out += ["/// Opcodes, in the exact numeric order of the reference implementation.",
            "#[repr(u8)]", "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub enum OpCode {"]
    out += [f"    {camel(r[6])} = {i}," for i, r in enumerate(rows)]
    # Padding: the opcode field is 7 bits wide, so every raw value is a valid `OpCode`. The
    # interpreter dispatches on all 128 values without a range check (a jump table of 128 entries)
    # and treats the reserved ones as corrupt bytecode.
    out += [f"    Reserved{i} = {i}," for i in range(len(rows), 128)]
    out += ["}", "", f"pub const NUM_OPCODES: usize = {len(rows)};", "",
            "/// Per-opcode properties: (mm: is metamethod-call follower, ot: sets top (out), it: uses top (in), t: test, a: sets register A, mode).",
            "#[derive(Clone, Copy, Debug)]",
            "pub struct OpProps { pub mm: bool, pub ot: bool, pub it: bool, pub t: bool, pub a: bool, pub mode: OpMode }", "",
            "pub const OP_PROPS: [OpProps; NUM_OPCODES] = ["]
    for r in rows:
        mm,ot,it,t,a,mode,_ = r
        out.append(f"    OpProps {{ mm: {str(mm=='1').lower()}, ot: {str(ot=='1').lower()}, it: {str(it=='1').lower()}, t: {str(t=='1').lower()}, a: {str(a=='1').lower()}, mode: OpMode::{modes[mode]} }},")
    out += ["];", "", "pub const OP_NAMES: [&str; NUM_OPCODES] = ["]
    out += [f'    "{r[6]}",' for r in rows]
    out += ["];", ""]
    d = root/f"crates/rn-core/src/ver/{short}"; d.mkdir(parents=True, exist_ok=True)
    (d/"opcodes_gen.rs").write_text("\n".join(out))
    print(ver, len(rows), "opcodes ->", d/"opcodes_gen.rs")
