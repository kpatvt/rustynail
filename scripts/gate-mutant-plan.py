#!/usr/bin/env python3
"""Chooses the mutant groups of scripts/gate-light.sh from the files a change touches (docs/GATES.md, "Changed files -> mutant groups").

  gate-mutant-plan.py [--base REF] [--files F...] [--jobs N] [--default NAMES] [--quiet]

Input: `git diff --name-only <base>` (plus untracked files; or --files), scripts/gate-mutant-map.tsv (sites and detectors of every mutant,
generated by scripts/gen-mutant-map.py from the registry and the TABLE of tests/tr_mutants.rs; a stale file is regenerated in memory with a
warning) and scripts/gate-mutant-times.tsv (seconds per mutant of the last full run).

A changed file selects
  * source file: the mutants whose injection site is in the enclosing function of a changed line (or on a changed line); when none of
    its sites is hit, the 6 sites nearest to the changed lines; plus the mutants of the same-named test binary (src/tr/shape.rs ->
    tests/tr_shape.rs and the mutants named `shape_*`);
  * test file with detector rows: the mutants of the detecting tests that changed (enclosing function of a changed line); changes in
    helpers / program tables (not a detecting test) select the detectors of the file whose name starts like the file (`h2_progs.rs` ->
    tests `h2_*`), else every mutant of the binary, at most --cap of them (the ones whose detectors are fastest);
  * any diff hunk that mentions a registered mutant name (registry, TABLE, comments): that mutant.
Nothing selected (docs, scripts, other crates): the small default set (fast mutants of different families). A mutant whose detector file
or test changed is always in the plan.
Output: explanation on stderr (unless --quiet), the final line on stdout: `PATTERNS=<comma list for TR_MUT_ONLY>` (empty: none)
and `ESTIMATE=<seconds>`."""
import argparse
import importlib.util
import os
import re
import statistics
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("genmap", os.path.join(ROOT, "scripts", "gen-mutant-map.py"))
genmap = importlib.util.module_from_spec(spec)
spec.loader.exec_module(genmap)

# fast mutants of different families, used when nothing maps (checked against the registry; times in the times file are 2-20 s)
DEFAULT = ["snap_drop_last", "phi_swap", "fold_nan", "tbar_skip", "poll_skip", "entry_no_typecheck", "alias_may_as_no", "native_ci_skip"]
BASELINE_S = 60  # the baseline pass (each detecting test once without a mutant) of a group run: measured 30-200 s, see GATES.md


def git(*a):
    r = subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True)
    return r.returncode, r.stdout.strip()


def default_base():
    rc, mb = git("merge-base", "HEAD", "origin/main")
    rc2, head = git("rev-parse", "HEAD")
    if rc == 0 and mb and mb != head:
        return mb
    return "HEAD~1"


def load_map():
    text, names, rows = genmap.generate()
    try:
        cur = open(genmap.OUT, encoding="utf-8").read()
    except OSError:
        cur = ""
    if cur != text:
        sys.stderr.write("gate-mutant-plan: WARNING scripts/gate-mutant-map.tsv is stale (run scripts/gen-mutant-map.py); using fresh data\n")
    return names, rows


def load_times(path):
    t = {}
    try:
        for l in open(path, encoding="utf-8"):
            p = l.rstrip("\n").split("\t")
            if len(p) >= 2:
                try:
                    t[p[0]] = float(p[1])
                except ValueError:
                    pass
    except OSError:
        pass
    return t


def fn_at(lines, n):
    """enclosing fn name of 1-based line n (nearest preceding fn item)"""
    fn = "-"
    for i in range(min(n, len(lines))):
        m = genmap.FN_RE.match(lines[i])
        if m:
            fn = m.group(1)
    return fn


def hunks(base, path):
    """[(new_start, new_end)] of the changed ranges in the current file, and the added/removed text"""
    rc, out = git("diff", "-U0", base, "--", path)
    hs, text = [], []
    for l in out.split("\n"):
        m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", l)
        if m:
            s = int(m.group(1))
            c = int(m.group(2)) if m.group(2) is not None else 1
            hs.append((s, max(s, s + c - 1)))
        elif l[:1] in "+-" and not l.startswith(("+++", "---")):
            text.append(l[1:])
    return hs, "\n".join(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base")
    ap.add_argument("--files", nargs="*")
    ap.add_argument("--jobs", type=int, default=7)
    ap.add_argument("--cap", type=int, default=40)
    ap.add_argument("--default")
    ap.add_argument("--times", default=os.path.join(ROOT, "scripts", "gate-mutant-times.tsv"))
    ap.add_argument("--show", type=int, default=20, help="mutants listed in the explanation (slowest first)")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--patterns", help="no selection: only the estimate for these TR_MUT_ONLY patterns")
    a = ap.parse_args()
    say = (lambda *x: None) if a.quiet else (lambda *x: print(*x, file=sys.stderr))

    sel = {}  # mutant -> reason
    names, rows = load_map()
    nameset = set(names)
    times = load_times(a.times)
    known = list(times.values())
    med = statistics.median(known) if known else 30.0
    sites, dets = {}, {}
    for kind, p, fn, line, n in rows:
        (sites if kind == "site" else dets).setdefault(p, []).append((fn, int(line), n))
    bins = {}  # tests/<bin> -> [(test, mutant)]
    for p, lst in dets.items():
        m = re.match(r"crates/rn-jit/tests/([a-z0-9_]+)(?:\.rs|/)", p)
        if m:
            bins.setdefault(m.group(1), []).extend((t, n) for t, _, n in lst)

    if a.patterns:
        changed = []
        base = None
        for p in a.patterns.split(","):
            for n in names:
                if p in n:
                    sel[n] = f"pattern {p}"
    elif a.files is not None:
        changed = a.files
        base = None
    else:
        base = a.base or default_base()
        rc, out = git("diff", "--name-only", base)
        changed = [f for f in out.split("\n") if f]
        rc, out = git("ls-files", "-o", "--exclude-standard")
        changed += [f for f in out.split("\n") if f and f not in changed]
        say(f"base {base}: {len(changed)} changed file(s)")

    def add(n, why):
        sel.setdefault(n, why)

    def fastest(group, cap):
        return sorted(group, key=lambda n: times.get(n, med))[:cap]

    for f in changed:
        text_of_file = None
        if a.files is None and os.path.exists(os.path.join(ROOT, f)) and f.endswith(".rs"):
            text_of_file = open(os.path.join(ROOT, f), encoding="utf-8").read().split("\n")
            hs, difftext = hunks(base, f)
        else:
            hs, difftext = [], ""
        # (1) mutant names mentioned in the changed text
        for n in nameset:
            if difftext and (f'"{n}"' in difftext or f"`{n}`" in difftext):
                add(n, f"named in the diff of {f}")
        stem = os.path.splitext(os.path.basename(f))[0]
        in_src = bool(re.match(r"crates/[^/]+/src/", f))
        in_tests = f.startswith("crates/rn-jit/tests/")
        # (2) source file: sites by enclosing function / nearest
        if in_src and f in sites:
            fns = {fn_at(text_of_file, n) for s, e in hs for n in (s, e)} if text_of_file else set()
            hit = [(fn, ln, n) for fn, ln, n in sites[f] if (fn in fns and fn != "-") or any(s <= ln <= e for s, e in hs)]
            if not hs:  # no hunk information (--files): the whole file
                hit = sites[f]
            if not hit and hs:
                dist = lambda ln: min(abs(ln - s) if ln < s else abs(ln - e) if ln > e else 0 for s, e in hs)
                hit = sorted(sites[f], key=lambda r: dist(r[1]))[:6]
                for _, _, n in hit:
                    add(n, f"nearest injection site to the change in {f}")
            for fn, ln, n in hit:
                add(n, f"site in {f}:{fn}")
        # (3) same-named detector binary and name prefix
        # (only for a file with few injection sites: for a big one the function-level choice above is the precise one)
        if in_src and not f.startswith("crates/rn-jit/src/tr/mutants") and len(sites.get(f, [])) <= 5:
            b = "tr_" + stem
            for _, n in bins.get(b, []):
                add(n, f"detector binary {b} of {f}")
            for n in names:
                if n.startswith(stem + "_"):
                    add(n, f"name prefix {stem}_ of {f}")
        # (4) test files with detector rows
        if in_tests and not f.endswith("tr_mutants.rs"):
            m = re.match(r"crates/rn-jit/tests/([a-z0-9_]+)(?:\.rs|/)", f)
            b = m.group(1) if m else None
            fns = {fn_at(text_of_file, n) for s, e in hs for n in (s, e)} if text_of_file else set()
            attributed = False
            for fn, _, n in dets.get(f, []):
                if fn == "*" or fn in fns or not hs:
                    add(n, f"detector {b}::{fn} changed")
                    attributed = attributed or fn != "*"
            if b in bins and not attributed:
                # a change outside a detecting test (helper, program table, new test): the detectors whose test name starts like the
                # file (`h2_progs.rs` -> `h2_*`) when the file is not the binary's main file, else the binary's fastest mutants
                pre_name = re.sub(r"_progs?$", "", stem)
                cand = [(t, n) for t, n in bins[b] if t.startswith(pre_name + "_")] if stem != b else []
                if cand:
                    for t, n in cand:
                        add(n, f"detector {b}::{t} (prefix of {os.path.basename(f)})")
                else:
                    allm = sorted({n for _, n in bins[b]})
                    for n in fastest(allm, a.cap):
                        add(n, f"binary {b} changed outside a detecting test" + (f" (capped to {a.cap} of {len(allm)})" if len(allm) > a.cap else ""))

    if not sel and not a.patterns:
        d = [n for n in (a.default.split(",") if a.default else DEFAULT) if n in nameset]
        for n in d:
            add(n, "default set (nothing maps)")
        say("nothing maps to a mutant: default set")

    # patterns: a name prefix `x_` when every registry name containing it is selected and it covers >= 3 selected names
    chosen = set(sel)
    pats = a.patterns.split(",") if a.patterns else []
    covered = set()
    cand = {}
    for n in sorted(chosen):
        i = n.find("_")
        if i > 0:
            cand.setdefault(n[: i + 1], set()).add(n)
    for p, ms in ([] if a.patterns else sorted(cand.items(), key=lambda kv: -len(kv[1]))):
        m_all = {x for x in names if p in x}
        if len(ms) >= 3 and m_all <= chosen and not m_all <= covered:
            pats.append(p)
            covered |= m_all
    for n in ([] if a.patterns else sorted(chosen - covered)):
        # exact names are substrings: they must not drag in a longer name that is not selected
        extra = {x for x in names if n in x} - chosen
        pats.append(n)
        covered |= {x for x in names if n in x}
        if extra:
            chosen |= extra
    eff = {x for x in names if any(p in x for p in pats)}
    ts = [times.get(n, med) for n in eff]
    unk = sum(1 for n in eff if n not in times)
    est = (max(sum(ts) / a.jobs, max(ts)) if ts else 0) + (BASELINE_S if ts else 0)
    order = sorted(eff, key=lambda n: -times.get(n, med))
    for n in order[:a.show]:
        say(f"  {n:<34} {times.get(n, med):6.1f}s  {sel.get(n, 'covered by a pattern')}")
    if len(order) > a.show:
        say(f"  ... {len(order) - a.show} more (--show N)")
    say(f"{len(eff)} mutant(s), sum {sum(ts):.0f}s, slowest {max(ts) if ts else 0:.0f}s, {unk} without a recorded time, "
        f"estimate {est:.0f}s on {a.jobs} jobs (incl. {BASELINE_S}s baseline)")
    say(f"patterns ({len(pats)}): {','.join(pats) if len(pats) <= 12 else ','.join(pats[:12]) + ',...'}")
    print(f"PATTERNS={','.join(pats)}")
    print(f"ESTIMATE={est:.0f}")


if __name__ == "__main__":
    main()
