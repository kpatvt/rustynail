#!/bin/bash
# Compare rnlua (release, JIT on) vs node vs LuaJIT on the programs that have a JS port in bench/js/.
# Usage (always under a memory cap, see CLAUDE.md):
#   cargo build --release -p rn-cli
#   systemd-run --user --scope -q -p MemoryMax=8G -p MemorySwapMax=0 timeout 3000 bench/js/run.sh [-n RUNS] [-o OUTDIR] [names...]
# Per program: output of node and rnlua is diffed first (a mismatch is reported and the program is skipped), then
# RUNS runs (default 5) of each engine pinned to one core (taskset -c 4) under `perf stat -e cycles:u,instructions:u`;
# the minimum cycles / instructions / wall time over the runs is kept.  RUSTYNAIL_SEED=0.
# Results: OUTDIR/raw.tsv and RESULTS.md (generated by mk_table.py).  Node numbers include its startup (~one empty
# script is measured too and reported); LuaJIT is skipped for programs it cannot run or whose output differs.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
RUNS=5
OUT=$HERE
CPU=4
SCALE=1
while getopts "n:o:c:s:" o; do
  case $o in n) RUNS=$OPTARG;; o) OUT=$OPTARG;; c) CPU=$OPTARG;; s) SCALE=$OPTARG;; *) exit 2;; esac
done
shift $((OPTIND - 1))

RN=$ROOT/target/release/rnlua
LJ=$(command -v luajit || true)
[ -x "$RN" ] || { echo "build first: cargo build --release -p rn-cli" >&2; exit 1; }
export RUSTYNAIL_SEED=0

# name -> Lua program (relative to bench/)
PROGS="
binary_trees:programs/binary_trees.lua
fannkuch:programs/fannkuch.lua
fib:programs/fib.lua
heapsort:programs/heapsort.lua
mandelbrot:programs/mandelbrot.lua
matmul:programs/matmul.lua
nbody:programs/nbody.lua
queens:programs/queens.lua
sieve:programs/sieve.lua
spectral_norm:programs/spectral_norm.lua
bounce:awfy/bounce.lua
list:awfy/list.lua
permute:awfy/permute.lua
storage:awfy/storage.lua
towers:awfy/towers.lua
richards:awfy/richards.lua
deltablue:awfy/deltablue.lua
cd:awfy/cd.lua
havlak:awfy/havlak.lua
json:awfy/json.lua
events:apps/events.lua
raytrace:apps/raytrace.lua
lru_cache:apps/lru_cache.lua
expr_lang:apps/expr_lang.lua
closures:programs/closures.lua
pcall_error:programs/pcall_error.lua
table_array:programs/table_array.lua
table_hash:programs/table_hash.lua
fasta:programs/fasta.lua
knucleotide:programs/knucleotide.lua
classic_vector:corpus/classic_vector.lua
lua_lexer:corpus/lua_lexer.lua
dijkstra_routes:corpus2/heldout/dijkstra_routes.lua
"

# -s K: run K times the default workload (argument N*K to Lua, JS and LuaJIT alike) for the programs whose default
# run is so short that node startup/warm-up dominates; only the programs listed here take part in a scaled run.
# (dijkstra_routes: the argument N sets both the graph size and the number of queries, so its cost grows with N^2;
# 20 * SCALE keeps -s 20 at N=400, i.e. about 4x the default run instead of 400x.)
declare -A DEFN=([bounce]=350 [list]=350 [permute]=100 [storage]=45 [towers]=45 [richards]=25 [deltablue]=20 [cd]=1
  [havlak]=6 [json]=35 [events]=85000 [raytrace]=2 [lru_cache]=90000 [expr_lang]=6
  [classic_vector]=1000 [lua_lexer]=50 [dijkstra_routes]=20)

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"
RAW=$OUT/raw.tsv
printf 'name\tengine\tstatus\tcycles\tinstr\twall_s\n' > "$RAW"

# measure ENGINE-LABEL DIR CMD...: min over RUNS of cycles/instr/wall; prints "cycles instr wall"
measure() {
  local dir=$1; shift
  local bc="" bi="" bw="" c i w t0 t1
  for ((r = 0; r < RUNS; r++)); do
    t0=$EPOCHREALTIME
    (cd "$dir" && taskset -c "$CPU" perf stat -x, -e cycles:u,instructions:u -o "$TMP/ps" "$@" </dev/null >/dev/null 2>&1)
    t1=$EPOCHREALTIME
    c=$(awk -F, '/cycles:u/{print $1}' "$TMP/ps")
    i=$(awk -F, '/instructions:u/{print $1}' "$TMP/ps")
    w=$(awk -v a="$t0" -v b="$t1" 'BEGIN{printf "%.4f", b-a}')
    if [ -z "$bc" ] || [ "$c" -lt "$bc" ]; then bc=$c; fi
    if [ -z "$bi" ] || [ "$i" -lt "$bi" ]; then bi=$i; fi
    if [ -z "$bw" ] || awk -v a="$w" -v b="$bw" 'BEGIN{exit !(a<b)}'; then bw=$w; fi
  done
  echo "$bc $bi $bw"
}

# node startup baseline (empty script)
: > "$TMP/empty.js"
read -r c i w < <(measure "$TMP" node "$TMP/empty.js")
printf 'EMPTY\tnode\tok\t%s\t%s\t%s\n' "$c" "$i" "$w" >> "$RAW"

for entry in $PROGS; do
  name=${entry%%:*}
  lua=${entry#*:}
  if [ $# -gt 0 ]; then case " $* " in *" $name "*) ;; *) continue;; esac; fi
  ARG=()
  if [ "$SCALE" != 1 ]; then
    [ -n "${DEFN[$name]:-}" ] || continue
    ARG=($((DEFN[$name] * SCALE)))
  fi
  ldir=$ROOT/bench/$(dirname "$lua")
  lfile=$(basename "$lua")
  js=$HERE/$name.js
  expect=$(cd "$ldir" && "$RN" "$lfile" "${ARG[@]}" </dev/null 2>&1)
  got=$(node "$js" "${ARG[@]}" </dev/null 2>&1)
  if [ "$expect" != "$got" ]; then
    echo "MISMATCH $name: lua='$expect' js='$got'" >&2
    printf '%s\tall\tmismatch\t\t\t\n' "$name" >> "$RAW"
    continue
  fi
  echo "== $name" >&2
  read -r c i w < <(measure "$ldir" "$RN" "$lfile" "${ARG[@]}")
  printf '%s\trnlua\tok\t%s\t%s\t%s\n' "$name" "$c" "$i" "$w" >> "$RAW"
  read -r c i w < <(measure "$HERE" node "$js" "${ARG[@]}")
  printf '%s\tnode\tok\t%s\t%s\t%s\n' "$name" "$c" "$i" "$w" >> "$RAW"
  if [ -n "$LJ" ]; then
    ljout=$(cd "$ldir" && "$LJ" "$lfile" "${ARG[@]}" </dev/null 2>&1)
    if [ "$ljout" = "$expect" ]; then
      read -r c i w < <(measure "$ldir" "$LJ" "$lfile" "${ARG[@]}")
      printf '%s\tluajit\tok\t%s\t%s\t%s\n' "$name" "$c" "$i" "$w" >> "$RAW"
    else
      printf '%s\tluajit\tn/a\t\t\t\n' "$name" >> "$RAW"
    fi
  fi
done

{ echo "node: $(node --version); $("$RN" --version | head -1); ${LJ:+$($LJ -v | cut -d' ' -f1-2)}; runs=$RUNS cpu=$CPU"; } > "$OUT/env.txt"
python3 -I "$HERE/mk_table.py" "$RAW" "$OUT/env.txt" > "$OUT/RESULTS.table.md"
echo "wrote $RAW and $OUT/RESULTS.table.md" >&2
