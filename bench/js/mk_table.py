#!/usr/bin/env python3
"""Turn raw.tsv (from run.sh) into a markdown table sorted by ours/node cycle ratio, worst first."""
import sys

raw, envf = sys.argv[1], sys.argv[2]
rows = {}
empty = None
for line in open(raw).read().splitlines()[1:]:
    f = line.split("\t")
    name, eng, status = f[0], f[1], f[2]
    if name == "EMPTY":
        empty = (int(f[3]), float(f[5]))
        continue
    d = rows.setdefault(name, {})
    if status == "ok":
        d[eng] = (int(f[3]), int(f[4]), float(f[5]))
    else:
        d[eng] = status

# the per-program note (what dominates) is looked up in notes.tsv next to this script when present
notes = {}
try:
    import os
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "notes.tsv")
    for l in open(p).read().splitlines():
        if l.strip() and not l.startswith("#"):
            k, v = l.split("\t", 1)
            notes[k] = v
except OSError:
    pass

def mc(x):
    return "%.0f" % (x / 1e6)

out = []
out.append("<!-- generated by bench/js/run.sh -> mk_table.py -->")
out.append(open(envf).read().strip())
out.append("")
if empty:
    out.append("Empty node script: %s Mcycles, %.3f s (included in every node number below; the `node-ex` ratio subtracts it)." % (mc(empty[0]), empty[1]))
    out.append("")
out.append("| program | rnlua Mcyc | node Mcyc | LuaJIT Mcyc | rnlua/node | rnlua/node-ex | rnlua/LuaJIT | rnlua s | node s | LuaJIT s | note |")
out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
lst = []
for name, d in rows.items():
    r, n, l = d.get("rnlua"), d.get("node"), d.get("luajit")
    if not isinstance(r, tuple) or not isinstance(n, tuple):
        lst.append((-1.0, name, d))
        continue
    lst.append((r[0] / n[0], name, d))
lst.sort(key=lambda t: -t[0])
for ratio, name, d in lst:
    r, n, l = d.get("rnlua"), d.get("node"), d.get("luajit")
    if not isinstance(r, tuple) or not isinstance(n, tuple):
        out.append("| %s | output mismatch | | | | | | | | | |" % name)
        continue
    nex = max(n[0] - (empty[0] if empty else 0), 1)
    lj = isinstance(l, tuple)
    out.append("| %s | %s | %s | %s | %.2f | %.2f | %s | %.3f | %.3f | %s | %s |" % (
        name, mc(r[0]), mc(n[0]), mc(l[0]) if lj else "n/a", r[0] / n[0], r[0] / nex,
        ("%.2f" % (r[0] / l[0])) if lj else "n/a", r[2], n[2], ("%.3f" % l[2]) if lj else "n/a", notes.get(name, "")))
print("\n".join(out))
